import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";
import { apart, dependencyKey, enterRequest, type RequestContext } from "../src/context.ts";
import { ErrorFingerprintCache } from "../src/errors.ts";
import { FingerprintCache } from "../src/fingerprint.ts";
import { PRISMA_PROVIDERS, patchPrisma } from "../src/instrument/prisma.ts";
import type { Logger } from "../src/log.ts";
import { CLIENT_REQUEST, generatePrisma, type PrismaLayout } from "./support/prisma-client.ts";

/**
 * Prisma 4 to 6 through its engine (ADR 0241): a real client, generated by the workspace's `prisma` 6 on a SQLite file,
 * whose operations reach the database through Prisma's own engine and no driver of Node's. The same shape was read in
 * 4.16 and 5.22, by hand: the operation, its model and its arguments reach `_executeRequest` as they do here. How the
 * class is found at the first request is `instrument-prisma-arm.test.ts`'s, in a process of its own.
 */

const quiet: Logger = { warn: () => {}, debug: () => {} };
const handed: unknown[] = [];
const internalError = (err: unknown): void => {
  handed.push(err);
};
afterEach(() => {
  expect(handed.splice(0), "the instrumentation failed while recording").toEqual([]);
});

async function inRequest(fn: () => Promise<void>): Promise<RequestContext> {
  return apart(async () => {
    const ctx = enterRequest();
    await fn();
    return ctx;
  });
}

const operationsOf = (ctx: RequestContext) =>
  [...(ctx.operations?.values() ?? [])].filter((o) => o.kind === "query").map((o) => [o.text, o.count, o.errors]);
const workOf = (ctx: RequestContext, kind: "postgres" | "mysql" | "sqlite" | "mssql" | "mongodb") =>
  ctx.work?.get(dependencyKey(kind, ""));

function deps() {
  return {
    log: quiet,
    internalError,
    fingerprints: {
      postgres: new FingerprintCache(100, "postgres"),
      mysql: new FingerprintCache(100, "mysql"),
      sqlite: new FingerprintCache(100, "sqlite"),
      mssql: new FingerprintCache(100, "mssql"),
    },
    errors: new ErrorFingerprintCache(),
  };
}

// biome-ignore lint/suspicious/noExplicitAny: the generated client's types are the project's, not the test's.
type Client = any;

/** A project directory with a client generated into it, and the `require` its application would have. */
async function project(layout: PrismaLayout): Promise<{ dir: string; require: NodeJS.Require }> {
  const dir = await mkdtemp(join(tmpdir(), `dt-prisma-${layout}-`));
  await generatePrisma(dir, layout, join(dir, "app.db"));
  await writeFile(join(dir, "app.js"), "");
  return { dir, require: createRequire(join(dir, "app.js")) };
}

describe("a client prisma-client-js generated, on SQLite", () => {
  let dir: string;
  let prisma: Client;

  beforeAll(async () => {
    const made = await project("output");
    dir = made.dir;
    const { PrismaClient } = made.require(CLIENT_REQUEST.output);
    expect(patchPrisma(PrismaClient, "test", deps())).toBe(true);
    prisma = new PrismaClient();
    // Outside any request, as an application seeds its database at start-up: not counted.
    for (const email of ["ana@example.com", "bo@example.com", "cy@example.com"]) {
      await prisma.user.create({ data: { email, posts: { create: [{ title: "hello" }] } } });
    }
  }, 60_000);

  afterAll(async () => {
    await prisma?.$disconnect();
    await rm(dir, { recursive: true, force: true });
  });

  it("names each operation by its action and its model, under the dependency its datasource is", async () => {
    const ctx = await inRequest(async () => {
      const users = await prisma.user.findMany();
      for (const user of users) await prisma.post.findMany({ where: { authorId: user.id } });
    });
    expect(operationsOf(ctx)).toEqual([
      ["findMany User", 1, 0],
      ["findMany Post", 3, 0],
    ]);
    expect(workOf(ctx, "sqlite")).toMatchObject({ calls: 4, errors: 0 });
  });

  it("counts an operation with an include as one: what the code asked for", async () => {
    const ctx = await inRequest(async () => {
      await prisma.user.findMany({ include: { posts: true } });
    });
    expect(operationsOf(ctx)).toEqual([["findMany User", 1, 0]]);
  });

  it("counts each findUnique a tick batches, as the code wrote them", async () => {
    const ctx = await inRequest(async () => {
      await Promise.all([1, 2, 3].map((id) => prisma.user.findUnique({ where: { id } })));
    });
    expect(operationsOf(ctx)).toEqual([["findUnique User", 3, 0]]);
  });

  it("reads a raw query's SQL as SQLite, and never its values", async () => {
    const secret = "hunter2-zq@example.com";
    const ctx = await inRequest(async () => {
      await prisma.$queryRaw`select "id" from "User" where "email" = ${secret}`;
      await prisma.$queryRawUnsafe(`select "id" from "User" where "email" = '${secret}'`);
      await prisma.$executeRaw`update "Post" set "title" = ${secret} where "id" = ${1}`;
    });
    const operations = operationsOf(ctx);
    expect(operations).toEqual([
      ['select "id" from "User" where "email" = ?', 2, 0],
      ['update "Post" set "title" = ? where "id" = ?', 1, 0],
    ]);
    expect(JSON.stringify(operations)).not.toContain("hunter2");
  });

  it("counts every operation of a transaction, a list of them or a function", async () => {
    const ctx = await inRequest(async () => {
      await prisma.$transaction([prisma.user.count(), prisma.post.count()]);
      await prisma.$transaction(async (tx: Client) => {
        await tx.user.findFirst();
        await tx.post.count();
      });
    });
    expect(operationsOf(ctx)).toEqual([
      ["count User", 1, 0],
      ["count Post", 2, 0],
      ["findFirst User", 1, 0],
    ]);
  });

  it("counts what a client extended with $extends runs", async () => {
    const extended = prisma.$extends({
      query: { $allModels: { $allOperations: ({ args, query }: Client) => query(args) } },
    });
    const ctx = await inRequest(async () => {
      await extended.user.count();
    });
    expect(operationsOf(ctx)).toEqual([["count User", 1, 0]]);
  });

  it("records a failed operation, and the application gets Prisma's error untouched", async () => {
    let thrown: unknown;
    const ctx = await inRequest(async () => {
      try {
        await prisma.user.create({ data: { email: "ana@example.com" } });
      } catch (err) {
        thrown = err;
      }
    });
    expect((thrown as { code?: unknown }).code).toBe("P2002");
    expect(operationsOf(ctx)).toEqual([["create User", 1, 1]]);
    expect(workOf(ctx, "sqlite")).toMatchObject({ calls: 1, errors: 1 });
  });

  it("records nothing outside a request", async () => {
    const ctx = await inRequest(async () => {});
    await prisma.user.count();
    expect(operationsOf(ctx)).toEqual([]);
  });

  it("patches once, however many times it is asked", async () => {
    const { PrismaClient } = createRequire(join(dir, "app.js"))(CLIENT_REQUEST.output);
    expect(patchPrisma(PrismaClient, "test", deps())).toBe(true);
    const ctx = await inRequest(async () => {
      await prisma.user.count();
    });
    expect(operationsOf(ctx)).toEqual([["count User", 1, 0]]);
  });
});

/**
 * What the class of a generated client has that the observer reads: the provider its schema names, and the adapter
 * a client given one keeps in its configuration. A real client of each would need a server of each.
 */
function fakeClient(provider: string, adapter?: object) {
  class PrismaClient {
    _activeProvider = provider;
    _engineConfig = { adapter };
    _executeRequest(params: { action: string }): Promise<unknown> {
      return params.action === "fails" ? Promise.reject(new Error("no")) : Promise.resolve([]);
    }
  }
  return PrismaClient;
}

describe("the dependency an operation is, by the provider of the datasource", () => {
  it.each(Object.entries(PRISMA_PROVIDERS))("puts %s's operations under %s", async (provider, kind) => {
    const Client = fakeClient(provider);
    expect(patchPrisma(Client, "test", deps())).toBe(true);
    const client = new Client();
    const ctx = await inRequest(async () => {
      await client._executeRequest({ action: "findMany", model: "Order", args: {} } as never);
    });
    expect(operationsOf(ctx)).toEqual([["findMany Order", 1, 0]]);
    expect(workOf(ctx, kind)).toMatchObject({ calls: 1 });
  });

  it.each([
    ["postgresql", "postgres", ['select * from "Order" where "id" = ', ' and "total" > ', ""], "$1", "$2"],
    ["mysql", "mysql", ["select * from `Order` where `id` = ", " and `total` > ", ""], "?", "?"],
    ["sqlite", "sqlite", ['select * from "Order" where "id" = ', ' and "total" > ', ""], "?", "?"],
    ["sqlserver", "mssql", ["select * from [Order] where [id] = ", " and [total] > ", ""], "@P1", "@P2"],
  ] as const)(
    "reads %s's raw SQL as %s reads it, with its own placeholders",
    async (provider, dialect, strings, ...marks) => {
      const Client = fakeClient(provider);
      patchPrisma(Client, "test", deps());
      const client = new Client();
      const ctx = await inRequest(async () => {
        await client._executeRequest({ action: "queryRaw", args: { strings, values: [7, 100] } } as never);
      });
      const sql = `${strings[0]}${marks[0]}${strings[1]}${marks[1]}${strings[2]}`;
      expect(operationsOf(ctx)).toEqual([[new FingerprintCache(10, dialect).get(sql).text, 1, 0]]);
    },
  );

  it("leaves a client with a driver adapter to the driver's own observer, which sees its SQL", async () => {
    const Client = fakeClient("postgresql", { provider: "postgres" });
    patchPrisma(Client, "test", deps());
    const client = new Client();
    const ctx = await inRequest(async () => {
      await client._executeRequest({ action: "findMany", model: "Order", args: {} } as never);
    });
    expect(operationsOf(ctx)).toEqual([]);
    expect(ctx.work).toBeUndefined();
  });

  it("counts nothing for a provider it does not know", async () => {
    const Client = fakeClient("oracle");
    patchPrisma(Client, "test", deps());
    const client = new Client();
    const ctx = await inRequest(async () => {
      await client._executeRequest({ action: "findMany", model: "Order", args: {} } as never);
    });
    expect(ctx.work).toBeUndefined();
  });

  it("counts against the dependency, and names nothing, what has no name a person wrote", async () => {
    const Client = fakeClient("postgresql");
    patchPrisma(Client, "test", deps());
    const client = new Client();
    const ctx = await inRequest(async () => {
      await client._executeRequest({ action: "findMany", model: "Order; drop", args: {} } as never);
      await client._executeRequest({ action: "queryRaw", args: { neither: "strings nor text" } } as never);
    });
    expect(operationsOf(ctx)).toEqual([["findMany ?", 1, 0]]);
    expect(workOf(ctx, "postgres")).toMatchObject({ calls: 2 });
  });

  it("says there is nothing to patch in what is not a generated client", () => {
    for (const nothing of [undefined, null, {}, class {}, () => {}]) {
      expect(patchPrisma(nothing, "test", deps())).toBe(false);
    }
  });
});
